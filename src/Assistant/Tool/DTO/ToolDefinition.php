namespace Madj2k\AiCore\Assistant\Tool\DTO;

/**
 * Class ToolDefinition
 *
 * Describes one provider-neutral model tool.
 *
 * @author Steffen Kroggel <developer@steffenkroggel.de>
 * @copyright Steffen Kroggel <developer@steffenkroggel.de>, Maximilian Fäßler <maximilian@faesslerweb.de>
 * @package Madj2k\AiCore
 * @license https://www.gnu.org/licenses/gpl-3.0.html GNU General Public License, version 3
 */
final readonly class ToolDefinition
{
    /**
     * Constructor.
     *
     * @param string $name Tool name.
     * @param string $description Tool description.
     * @param array<string, mixed> $inputSchema JSON Schema for tool arguments.
     */
    public function __construct(
        public string $name,
        public string $description = '',
        public array $inputSchema = [],
    ) {
    }

    /**
     * Converts the definition to the provider-neutral function-tool shape.
     *
     * @return array<string, mixed> Tool definition.
     */
    public function toArray(): array
    {
        return [
            'type' => 'function',
            'function' => [
                'name' => $this->name,
                'description' => $this->description,
                'parameters' => $this->inputSchema,
            ],
        ];
    }
}
